import path from 'node:path'
import { createHash } from 'node:crypto'
import type { IFileSystem } from '../../../../core/protocols/file-system'
import { ValidationError } from '../../../../core/errors/validation-error'

type Entry = { files: Record<string, string>; scripts: string[]; css: string }
type Entries = Record<string, Entry>
const digest = (content: string) => createHash('sha256').update(content).digest('hex')

export class OutputManifest {
  private previous: Entries = {}
  private next: Entries = {}
  private writes = new Map<string, string>()
  private readonly root: string
  private readonly manifestPath: string
  constructor(
    output: string,
    private readonly fs: IFileSystem,
  ) {
    this.root = path.resolve(output)
    this.manifestPath = path.join(this.root, '.liquidify-manifest.json')
  }

  public async begin(files: string[], changed: Set<string>): Promise<void> {
    if (await this.fs.exists(this.manifestPath)) {
      const stored = JSON.parse(await this.fs.readFile(this.manifestPath))
      if (stored.version !== 1 || !stored.entries || typeof stored.entries !== 'object')
        throw new ValidationError('Invalid output manifest.', this.manifestPath)
      this.previous = stored.entries
    }
    this.writes.clear()
    const active = new Set(files.map((file) => path.resolve(file)))
    for (const [source, entry] of Object.entries(this.previous)) {
      if (!active.has(source)) continue
      for (const relative of Object.keys(entry.files)) {
        if (!(await this.fs.exists(this.safePath(relative)))) {
          changed.add(source)
          break
        }
      }
    }
    this.next = Object.fromEntries(Object.entries(this.previous).filter(([file]) => active.has(file) && !changed.has(file)))
  }

  public async write(source: string, file: string, content: string): Promise<void> {
    source = path.resolve(source)
    const relative = path.relative(this.root, path.resolve(file))
    this.safePath(relative)
    if (['assets/react-runtime.js', 'snippets/script-global.liquid'].includes(relative.replace(/\\/g, '/'))) {
      throw new ValidationError(`Output path is reserved by Liquidify: ${relative}`, source)
    }
    for (const [owner, entry] of Object.entries(this.next)) {
      if (owner !== source && relative in entry.files)
        throw new ValidationError(`Output conflict: ${relative} is also generated by ${owner}.`, source)
    }
    this.writes.set(file, content)
    this.entry(source).files[relative] = digest(content)
  }

  public contributions(source: string, scripts: string[], css: string): void {
    Object.assign(this.entry(path.resolve(source)), { scripts, css })
  }

  private entry(source: string): Entry {
    this.next[source] ??= { files: {}, scripts: [], css: '' }
    return this.next[source]
  }

  private safePath(relative: string): string {
    const resolved = path.resolve(this.root, relative)
    if (
      !relative ||
      path.isAbsolute(relative) ||
      path.relative(this.root, resolved).startsWith('..') ||
      !/^(assets|sections|snippets|blocks)[/\\].+\.(js|liquid)$/.test(relative)
    ) {
      throw new ValidationError(`Unsafe output path in manifest: ${relative}`, this.manifestPath)
    }
    return resolved
  }

  public async finish(): Promise<void> {
    for (const [file, content] of this.writes) await this.fs.writeFile(file, content)
    const retained = new Set(Object.values(this.next).flatMap((entry) => Object.keys(entry.files)))
    for (const entry of Object.values(this.previous)) {
      for (const [relative, hash] of Object.entries(entry.files)) {
        if (retained.has(relative)) continue
        const file = this.safePath(relative)
        if ((await this.fs.exists(file)) && digest(await this.fs.readFile(file)) === hash) await this.fs.unlink(file)
      }
    }
    const entries = Object.entries(this.next)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([, entry]) => entry)
    const scripts = [...new Set(entries.flatMap((entry) => entry.scripts))]
      .map((script) => `<script src="{{ '${script}' | asset_url }}" defer></script>`)
      .join('\n')
    const css = [...new Set(entries.map((entry) => entry.css.trim()).filter(Boolean))].join('\n')
    await this.updateAggregate(
      'snippets/script-global.liquid',
      scripts,
      '{% comment %}liquidify:start{% endcomment %}',
      '{% comment %}liquidify:end{% endcomment %}',
    )
    await this.updateAggregate('assets/global.css', css, '/* liquidify:start */', '/* liquidify:end */')
    await this.fs.writeFile(this.manifestPath, JSON.stringify({ version: 1, entries: this.next }, null, 2))
    this.previous = structuredClone(this.next)
  }

  private async updateAggregate(relative: string, content: string, start: string, end: string): Promise<void> {
    const file = path.join(this.root, relative)
    const previous = (await this.fs.exists(file)) ? await this.fs.readFile(file) : ''
    const begin = previous.indexOf(start)
    const finish = previous.indexOf(end, begin)
    const managed = content ? `${start}\n${content}\n${end}` : ''
    const next =
      begin >= 0 && finish >= begin
        ? previous.slice(0, begin) + managed + previous.slice(finish + end.length)
        : previous + (managed ? `${previous && !previous.endsWith('\n') ? '\n' : ''}${managed}` : '')
    if (next !== previous) {
      await this.fs.mkdir(path.dirname(file), true)
      await this.fs.writeFile(file, next)
    }
  }
}
